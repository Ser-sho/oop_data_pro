    corridor = municipality or 'OOP Corridor'
    date_str = reporting_date.strftime('%d %B %Y') if hasattr(reporting_date, 'strftime') else str(reporting_date)
    period = period_covered or 'Not specified'
    close = close_time if isinstance(close_time, str) else close_time.strftime('%H:%M')
    coverage = f"{summary['ward_coverage_pct']:.1f}%" if summary['ward_coverage_pct'] is not None else 'Not configured'
    covered = summary['distinct_wards']
    total = summary['total_wards'] if summary['total_wards'] else '—'
    missing = summary['missing_wards'] if summary['missing_wards'] is not None else '—'
    voc = 'Not supplied'
    status = 'GREEN' if summary['invalid_case_records'] == 0 and (summary['ward_coverage_pct'] in (None, 100)) else 'AMBER'

    footer = f"{corridor} | INTERNAL OOP OPERATIONS REPORTING | {date_str} | {close}"
    common = {'[CORRIDOR NAME]': corridor, '[MUNICIPALITIES / REGIONS]': corridor, '[REPORTING DATE]': date_str, '[PERIOD COVERED]': period, '[DATA CLOSE TIME]': close, '[RAG]': status}
    for slide in prs.slides:
        _replace_text(slide, common)
        _set_shape_text(slide, f"{corridor} | INTERNAL SDI OPERATIONS REPORTING | {date_str} | {close}", footer)
        _set_shape_text(slide, 'Template: replace all [bracketed] fields and sample chart data', 'Generated by OOP Corridor Reporting System')

    # Slide 1
    s = prs.slides[0]
    _set_shape_text(s, '[##]', f"{summary['valid_cases']:,}")
    _set_shape_text(s, '[##/##]', f"{covered}/{total}")
    _set_shape_text(s, '[##%]', coverage)
    _set_shape_text(s, '[##]', str(missing))
    _set_shape_text(s, '[RAG]', status)
    _set_shape_text(s, 'VOC ready / done', 'VOC ready / done')
    # There are multiple [##] placeholders; set by position for the first slide.
    vals = [f"{summary['valid_cases']:,}", f"{covered}/{total}", coverage, str(missing), voc, status]
    placeholders = [sh for sh in s.shapes if hasattr(sh,'text') and sh.text.strip() in {'[##]','[##/##]','[##%]','[RAG]'}]
    for sh, val in zip(placeholders, vals): sh.text = val

    # Slide 2
    s = prs.slides[1]
    text_shapes = [sh for sh in s.shapes if hasattr(sh,'text')]
    _set_shape_text(s, '[##] valid cases opened [##] of [target] wards ([##%]). [Best-performing municipality/region] leads coverage; [largest gap] carries the largest missing-ward load.',
                    f"{summary['valid_cases']:,} valid cases are represented across {covered} of {total} configured wards ({coverage}).")
    _set_shape_text(s, '[Today / week-to-date] added [##] new wards and [##] cases compared with [previous close]. Note material increases or flat movement only.',
                    f"The current extract contains {summary['records']:,} records. Reporting-period comparison will be added once a prior-close dataset is supplied.")
    _set_shape_text(s, '[##] wards remain uncovered. Prioritise wards carried over from the previous close and any channel/time gaps affecting coverage.',
                    f"{missing} wards remain outside the represented-ward list based on the configured total. Prioritise validation of the missing-ward queue before circulation.")
    _set_shape_text(s, 'Replace with cases and new wards by day.', 'Cases by available Created On date')
    if analysis['dates'].get('available'):
        d=analysis['dates']['by_date'][['date','cases']].copy(); d['date']=d['date'].astype(str)
        _add_chart(s,d.head(10),0.75,3.85,3.6,1.55,'line','Cases by day',45)
    _set_shape_text(s, 'Recommended focus', 'Recommended focus')
    _set_shape_text(s, 'Assign missing wards by municipality/region.\nProtect high-yield calling times.\nMove detailed exceptions to addendum.',
                    'Validate missing wards against the official ward register.\nProtect peak intake hours.\nKeep detailed exceptions in the addendum.')

    # Slide 3
    s=prs.slides[2]
    _set_shape_text(s, 'Replace with stacked bars by municipality/region.', 'Represented vs missing wards')
    # Generic single-area table; multi-area mapping comes later when municipality field/reference mapping is added.
    rows = [[corridor, total, covered, missing, coverage], ['Total', total, covered, missing, coverage]]
    # Fill the four data rows by exact placeholder positions.
    ph = [sh for sh in s.shapes if hasattr(sh,'text') and sh.text.strip() in {'[Municipality/Region A]','[Municipality/Region B]','[Municipality/Region C]','Total'}]
    data_by_y = sorted([sh for sh in ph], key=lambda sh: sh.top)
    # Find adjacent value placeholders and populate by row based on y positions.
    for sh in s.shapes:
        if hasattr(sh,'text') and sh.text.strip() == '[Municipality/Region A]': sh.text=corridor
        elif hasattr(sh,'text') and sh.text.strip() == '[Municipality/Region B]': sh.text='Not available from mapped municipality field'
        elif hasattr(sh,'text') and sh.text.strip() == '[Municipality/Region C]': sh.text='Not available from mapped municipality field'
    # Replace remaining numeric placeholders by their vertical row.
    row_values={2:(total,covered,missing,coverage),2.71:(None,None,None,None),3.13:(None,None,None,None),3.56:(total,covered,missing,coverage)}
