    # Slide 6
    s=prs.slides[5]
    vals=['Not supplied','Not supplied','Not available','Not available','Not supplied']
    for sh in s.shapes:
        if hasattr(sh,'text') and sh.text.strip() in {'[##]','[##%]','[Status]'}:
            sh.text=vals.pop(0) if vals else 'Not supplied'
    _set_shape_text(s,'If no date-aligned VOC dataset is supplied, report availability as \'Not supplied\' and do not infer happiness, effort, satisfaction or NPS. Put anomaly detail in the addendum.',
                    'No date-aligned VOC dataset was supplied with this V1 extract. Happiness, effort, satisfaction and NPS are therefore not inferred.')

