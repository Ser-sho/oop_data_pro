from __future__ import annotations
from pathlib import Path
import tempfile
import pandas as pd
import matplotlib.pyplot as plt
from pptx import Presentation
from pptx.util import Inches


def _replace_text(slide, replacements):
    for shape in slide.shapes:
        if not hasattr(shape, 'text_frame'):
            continue
        txt = shape.text
        new = txt
        for old, val in replacements.items():
            new = new.replace(old, str(val))
        if new != txt:
            shape.text = new


def _find_shape(slide, text):
    for shape in slide.shapes:
        if hasattr(shape, 'text') and shape.text.strip() == text:
            return shape
    return None


def _set_shape_text(slide, old_text, new_text):
    s = _find_shape(slide, old_text)
    if s is not None:
        s.text = str(new_text)
        return True
    return False


def _add_chart(slide, df, x, y, w, h, kind='bar', title=None, rotate=0):
    if df is None or df.empty:
        return
    with tempfile.NamedTemporaryFile(suffix='.png', delete=False) as f:
        path = f.name
    fig = plt.figure(figsize=(7, 3.0), dpi=180)
    ax = fig.add_subplot(111)
    d = df.copy()
    labels = d.iloc[:,0].astype(str).tolist()
    vals = pd.to_numeric(d.iloc[:,1], errors='coerce').fillna(0).tolist()
    if kind == 'pie':
        ax.pie(vals, labels=labels, autopct='%1.0f%%', textprops={'fontsize':7})
    elif kind == 'line':
        ax.plot(range(len(vals)), vals, marker='o')
        ax.set_xticks(range(len(vals))); ax.set_xticklabels(labels, rotation=rotate, ha='right', fontsize=7)
        ax.set_ylabel('Cases')
    else:
        ax.bar(labels, vals)
        ax.tick_params(axis='x', labelrotation=rotate, labelsize=7)
        ax.set_ylabel('Cases')
    if title: ax.set_title(title, fontsize=10)
    ax.grid(axis='y', alpha=.2)
    fig.tight_layout()
    fig.savefig(path, bbox_inches='tight', transparent=True)
    plt.close(fig)
    slide.shapes.add_picture(path, Inches(x), Inches(y), Inches(w), Inches(h))
    Path(path).unlink(missing_ok=True)


def _table_rows(table, rows):
    for r, values in enumerate(rows, start=1):
        if r >= len(table.rows): break
        for c, value in enumerate(values):
            if c < len(table.columns):
                table.cell(r,c).text = str(value)


